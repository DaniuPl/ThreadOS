static volatile int polish;

void locale_set_language(const char *language)
{
    polish = language && !strcmp(language, "pl");
}

int locale_is_polish(void)
{
    return polish;
}

const char *locale_text(const char *english)
{
    if (!english || !polish)
        return english;

    for (unsigned i = 0; i < sizeof(translations) / sizeof(translations[0]);
         i++)
        if (!strcmp(english, translations[i].english))
            return translations[i].polish;
    return english;
}
