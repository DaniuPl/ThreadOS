/* cryptotest - cryptographic test vectors (the first brick under TLS)
 *
 * It checks SHA-256 (FIPS 180-4), HMAC-SHA256 (RFC 4231), HKDF
 * (RFC 5869), ChaCha20 and Poly1305 (RFC 8439) and X25519 (RFC 7748)
 * against the official vectors. Without that there is no point starting
 * on the handshake - an error in the cryptography shows up only as an
 * incomprehensible "decrypt error" from the server.
 */

#include "uapi.h"
#include "usha256.h"
#include "uchacha.h"
#include "ux25519.h"

static int failures;

static void print_hex(const uint8_t *p, uint32_t n)
{
    const char *hex = "0123456789abcdef";
    char buf[3] = {0, 0, 0};
    for (uint32_t i = 0; i < n; i++) {
        buf[0] = hex[p[i] >> 4];
        buf[1] = hex[p[i] & 15];
        print(buf);
    }
}

static int equal(const uint8_t *a, const uint8_t *b, uint32_t n)
{
    for (uint32_t i = 0; i < n; i++)
        if (a[i] != b[i])
            return 0;
    return 1;
}

static void check(const char *what, const uint8_t *got, const uint8_t *want,
                  uint32_t n)
{
    print(what);
    if (equal(got, want, n)) {
        print(": OK\n");
        return;
    }
    print(": BLAD\n  wyszlo:   ");
    print_hex(got, n);
    print("\n  a mialo:  ");
    print_hex(want, n);
    print("\n");
    failures++;
}

void _start(void)
{
    uint8_t out[64];

    print("[crypto] wektory testowe SHA-256 / HMAC / HKDF\n");

    /* SHA-256("abc") - FIPS 180-4 */
    static const uint8_t abc[] = {
        0xba,0x78,0x16,0xbf,0x8f,0x01,0xcf,0xea,0x41,0x41,0x40,0xde,0x5d,0xae,
        0x22,0x23,0xb0,0x03,0x61,0xa3,0x96,0x17,0x7a,0x9c,0xb4,0x10,0xff,0x61,
        0xf2,0x00,0x15,0xad };
    sha256("abc", 3, out);
    check("SHA-256('abc')", out, abc, 32);

    /* SHA-256 of an empty input */
    static const uint8_t empty[] = {
        0xe3,0xb0,0xc4,0x42,0x98,0xfc,0x1c,0x14,0x9a,0xfb,0xf4,0xc8,0x99,0x6f,
        0xb9,0x24,0x27,0xae,0x41,0xe4,0x64,0x9b,0x93,0x4c,0xa4,0x95,0x99,0x1b,
        0x78,0x52,0xb8,0x55 };
    sha256("", 0, out);
    check("SHA-256('')", out, empty, 32);

    /* SHA-256 of two blocks (448+ bits) - a padding test */
    static const uint8_t twoblk[] = {
        0x24,0x8d,0x6a,0x61,0xd2,0x06,0x38,0xb8,0xe5,0xc0,0x26,0x93,0x0c,0x3e,
        0x60,0x39,0xa3,0x3c,0xe4,0x59,0x64,0xff,0x21,0x67,0xf6,0xec,0xed,0xd4,
        0x19,0xdb,0x06,0xc1 };
    sha256("abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq", 56, out);
    check("SHA-256 (dwa bloki)", out, twoblk, 32);

    /* HMAC-SHA256, case 1 from RFC 4231 */
    uint8_t key[20];
    for (int i = 0; i < 20; i++)
        key[i] = 0x0b;
    static const uint8_t hmac1[] = {
        0xb0,0x34,0x4c,0x61,0xd8,0xdb,0x38,0x53,0x5c,0xa8,0xaf,0xce,0xaf,0x0b,
        0xf1,0x2b,0x88,0x1d,0xc2,0x00,0xc9,0x83,0x3d,0xa7,0x26,0xe9,0x37,0x6c,
        0x2e,0x32,0xcf,0xf7 };
    hmac_sha256(key, 20, "Hi There", 8, out);
    check("HMAC-SHA256 (RFC 4231 #1)", out, hmac1, 32);

    /* HMAC with a key longer than a block - case 6 from RFC 4231 */
    static uint8_t longkey[131];
    for (int i = 0; i < 131; i++)
        longkey[i] = 0xaa;
    static const uint8_t hmac6[] = {
        0x60,0xe4,0x31,0x59,0x1e,0xe0,0xb6,0x7f,0x0d,0x8a,0x26,0xaa,0xcb,0xf5,
        0xb7,0x7f,0x8e,0x0b,0xc6,0x21,0x37,0x28,0xc5,0x14,0x05,0x46,0x04,0x0f,
        0x0e,0xe3,0x7f,0x54 };
    hmac_sha256(longkey, 131,
                "Test Using Larger Than Block-Size Key - Hash Key First", 54,
                out);
    check("HMAC-SHA256 (RFC 4231 #6)", out, hmac6, 32);

    /* HKDF-SHA256, case 1 from RFC 5869 */
    uint8_t ikm[22], salt[13], info[10], prk[32];
    for (int i = 0; i < 22; i++)
        ikm[i] = 0x0b;
    for (int i = 0; i < 13; i++)
        salt[i] = (uint8_t)i;
    for (int i = 0; i < 10; i++)
        info[i] = (uint8_t)(0xf0 + i);

    static const uint8_t want_prk[] = {
        0x07,0x77,0x09,0x36,0x2c,0x2e,0x32,0xdf,0x0d,0xdc,0x3f,0x0d,0xc4,0x7b,
        0xba,0x63,0x90,0xb6,0xc7,0x3b,0xb5,0x0f,0x9c,0x31,0x22,0xec,0x84,0x4a,
        0xd7,0xc2,0xb3,0xe5 };
    hkdf_extract(salt, 13, ikm, 22, prk);
    check("HKDF-Extract (RFC 5869 #1)", prk, want_prk, 32);

    static const uint8_t want_okm[] = {
        0x3c,0xb2,0x5f,0x25,0xfa,0xac,0xd5,0x7a,0x90,0x43,0x4f,0x64,0xd0,0x36,
        0x2f,0x2a,0x2d,0x2d,0x0a,0x90,0xcf,0x1a,0x5a,0x4c,0x5d,0xb0,0x2d,0x56,
        0xec,0xc4,0xc5,0xbf,0x34,0x00,0x72,0x08,0xd5,0xb8,0x87,0x18,0x58,0x65 };
    hkdf_expand(prk, info, 10, out, 42);
    check("HKDF-Expand (RFC 5869 #1)", out, want_okm, 42);

    /* --- ChaCha20 (RFC 8439 2.4.2) --- */
    uint8_t ckey[32], cnonce[12];
    for (int i = 0; i < 32; i++)
        ckey[i] = (uint8_t)i;
    for (int i = 0; i < 12; i++)
        cnonce[i] = 0;
    cnonce[3] = 0x00;
    cnonce[7] = 0x4a;

    static const char plain[] =
        "Ladies and Gentlemen of the class of '99: If I could offer you "
        "only one tip for the future, sunscreen would be it.";
    static const uint8_t want_ct[] = {
        0x6e,0x2e,0x35,0x9a,0x25,0x68,0xf9,0x80,0x41,0xba,0x07,0x28,0xdd,0x0d,
        0x69,0x81,0xe9,0x7e,0x7a,0xec,0x1d,0x43,0x60,0xc2,0x0a,0x27,0xaf,0xcc,
        0xfd,0x9f,0xae,0x0b,0xf9,0x1b,0x65,0xc5,0x52,0x47,0x33,0xab,0x8f,0x59,
        0x3d,0xab,0xcd,0x62,0xb3,0x57,0x16,0x39,0xd6,0x24,0xe6,0x51,0x52,0xab,
        0x8f,0x53,0x0c,0x35,0x9f,0x08,0x61,0xd8,0x07,0xca,0x0d,0xbf,0x50,0x0d,
        0x6a,0x61,0x56,0xa3,0x8e,0x08,0x8a,0x22,0xb6,0x5e,0x52,0xbc,0x51,0x4d,
        0x16,0xcc,0xf8,0x06,0x81,0x8c,0xe9,0x1a,0xb7,0x79,0x37,0x36,0x5a,0xf9,
        0x0b,0xbf,0x74,0xa3,0x5b,0xe6,0xb4,0x0b,0x8e,0xed,0xf2,0x78,0x5e,0x42,
        0x87,0x4d };
    static uint8_t ct[114];
    chacha20_xor(ckey, 1, cnonce, (const uint8_t *)plain, ct, 114);
    check("ChaCha20 (RFC 8439 2.4.2)", ct, want_ct, 114);

    /* --- Poly1305 (RFC 8439 2.5.2) --- */
    static const uint8_t pkey[32] = {
        0x85,0xd6,0xbe,0x78,0x57,0x55,0x6d,0x33,0x7f,0x44,0x52,0xfe,0x42,0xd5,
        0x06,0xa8,0x01,0x03,0x80,0x8a,0xfb,0x0d,0xb2,0xfd,0x4a,0xbf,0xf6,0xaf,
        0x41,0x49,0xf5,0x1b };
    static const uint8_t want_tag[] = {
        0xa8,0x06,0x1d,0xc1,0x30,0x51,0x36,0xc6,0xc2,0x2b,0x8b,0xaf,0x0c,0x01,
        0x27,0xa9 };
    poly1305(pkey, (const uint8_t *)"Cryptographic Forum Research Group", 34,
             out);
    check("Poly1305 (RFC 8439 2.5.2)", out, want_tag, 16);

    /* --- AEAD ChaCha20-Poly1305 (RFC 8439 2.8.2) --- */
    static const uint8_t akey[32] = {
        0x80,0x81,0x82,0x83,0x84,0x85,0x86,0x87,0x88,0x89,0x8a,0x8b,0x8c,0x8d,
        0x8e,0x8f,0x90,0x91,0x92,0x93,0x94,0x95,0x96,0x97,0x98,0x99,0x9a,0x9b,
        0x9c,0x9d,0x9e,0x9f };
    static const uint8_t anonce[12] = {
        0x07,0x00,0x00,0x00,0x40,0x41,0x42,0x43,0x44,0x45,0x46,0x47 };
    static const uint8_t aad[12] = {
        0x50,0x51,0x52,0x53,0xc0,0xc1,0xc2,0xc3,0xc4,0xc5,0xc6,0xc7 };
    static const uint8_t want_atag[] = {
        0x1a,0xe1,0x0b,0x59,0x4f,0x09,0xe2,0x6a,0x7e,0x90,0x2e,0xcb,0xd0,0x60,
        0x06,0x91 };
    static uint8_t act[114], apt[114];
    uint8_t atag[16];
    aead_encrypt(akey, anonce, aad, 12, (const uint8_t *)plain, act, 114, atag);
    check("AEAD ChaCha20-Poly1305: znacznik", atag, want_atag, 16);

    int ok = aead_decrypt(akey, anonce, aad, 12, act, apt, 114, atag);
    if (!ok || !equal(apt, (const uint8_t *)plain, 114)) {
        print("AEAD odszyfrowanie: BLAD\n");
        failures++;
    } else {
        print("AEAD odszyfrowanie: OK\n");
    }

    atag[0] ^= 1;                        /* a swapped tag has to fall apart */
    if (aead_decrypt(akey, anonce, aad, 12, act, apt, 114, atag)) {
        print("AEAD wykrycie podmiany: BLAD (przeszlo mimo zmiany)\n");
        failures++;
    } else {
        print("AEAD wykrycie podmiany: OK\n");
    }

    /* --- X25519 (RFC 7748 5.2) --- */
    static const uint8_t sc[32] = {
        0xa5,0x46,0xe3,0x6b,0xf0,0x52,0x7c,0x9d,0x3b,0x16,0x15,0x4b,0x82,0x46,
        0x5e,0xdd,0x62,0x14,0x4c,0x0a,0xc1,0xfc,0x5a,0x18,0x50,0x6a,0x22,0x44,
        0xba,0x44,0x9a,0xc4 };
    static const uint8_t pt[32] = {
        0xe6,0xdb,0x68,0x67,0x58,0x30,0x30,0xdb,0x35,0x94,0xc1,0xa4,0x24,0xb1,
        0x5f,0x7c,0x72,0x66,0x24,0xec,0x26,0xb3,0x35,0x3b,0x10,0xa9,0x03,0xa6,
        0xd0,0xab,0x1c,0x4c };
    static const uint8_t want_shared[32] = {
        0xc3,0xda,0x55,0x37,0x9d,0xe9,0xc6,0x90,0x8e,0x94,0xea,0x4d,0xf2,0x8d,
        0x08,0x4f,0x32,0xec,0xcf,0x03,0x49,0x1c,0x71,0xf7,0x54,0xb4,0x07,0x55,
        0x77,0xa2,0x85,0x52 };
    x25519(out, sc, pt);
    check("X25519 (RFC 7748 5.2)", out, want_shared, 32);

    /* The shared secret computed from both sides has to come out the
   same */
    uint8_t priv_a[32], priv_b[32], pub_a[32], pub_b[32], sh_a[32], sh_b[32];
    for (int i = 0; i < 32; i++) {
        priv_a[i] = (uint8_t)(i + 1);
        priv_b[i] = (uint8_t)(200 - i);
    }
    x25519_base(pub_a, priv_a);
    x25519_base(pub_b, priv_b);
    x25519(sh_a, priv_a, pub_b);
    x25519(sh_b, priv_b, pub_a);
    check("X25519: obie strony licza ten sam sekret", sh_a, sh_b, 32);

    /* What one scalar multiplication costs - a TLS handshake needs two
       (the public key and the shared secret) */
    uint32_t t0 = sys_getticks();
    x25519_base(pub_a, priv_a);
    uint32_t t1 = sys_getticks();
    print("X25519: jedno mnozenie skalarne ~");
    print_dec((t1 - t0) * 10);
    print(" ms\n");

    if (failures) {
        print("[crypto] BLEDOW: ");
        print_dec((uint32_t)failures);
        print("\n");
        sys_exit(1);
    }
    print("[crypto] wszystkie wektory zgadzaja sie\n");
    sys_exit(0);
}
