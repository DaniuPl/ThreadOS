/* cryptotest - wektory testowe kryptografii (pierwsza cegielka pod TLS)
 *
 * Sprawdza SHA-256 (FIPS 180-4), HMAC-SHA256 (RFC 4231) i HKDF
 * (RFC 5869) na oficjalnych wektorach. Bez tego nie ma sensu zabierac
 * sie za handshake - blad w skrocie objawia sie dopiero jako
 * niezrozumiale "decrypt error" od serwera.
 */

#include "usys.h"
#include "usha256.h"

static int failures;

static void print_hex(const uint8_t *p, uint32_t n)
{
    const char *hex = "0123456789abcdef";
    char buf[3] = {0, 0, 0};
    for (uint32_t i = 0; i < n; i++) {
        buf[0] = hex[p[i] >> 4];
        buf[1] = hex[p[i] & 15];
        print(buf);
    }
}

static int equal(const uint8_t *a, const uint8_t *b, uint32_t n)
{
    for (uint32_t i = 0; i < n; i++)
        if (a[i] != b[i])
            return 0;
    return 1;
}

static void check(const char *what, const uint8_t *got, const uint8_t *want,
                  uint32_t n)
{
    print(what);
    if (equal(got, want, n)) {
        print(": OK\n");
        return;
    }
    print(": BLAD\n  wyszlo:   ");
    print_hex(got, n);
    print("\n  a mialo:  ");
    print_hex(want, n);
    print("\n");
    failures++;
}

void _start(void)
{
    uint8_t out[64];

    print("[crypto] wektory testowe SHA-256 / HMAC / HKDF\n");

    /* SHA-256("abc") - FIPS 180-4 */
    static const uint8_t abc[] = {
        0xba,0x78,0x16,0xbf,0x8f,0x01,0xcf,0xea,0x41,0x41,0x40,0xde,0x5d,0xae,
        0x22,0x23,0xb0,0x03,0x61,0xa3,0x96,0x17,0x7a,0x9c,0xb4,0x10,0xff,0x61,
        0xf2,0x00,0x15,0xad };
    sha256("abc", 3, out);
    check("SHA-256('abc')", out, abc, 32);

    /* SHA-256 pustego wejscia */
    static const uint8_t empty[] = {
        0xe3,0xb0,0xc4,0x42,0x98,0xfc,0x1c,0x14,0x9a,0xfb,0xf4,0xc8,0x99,0x6f,
        0xb9,0x24,0x27,0xae,0x41,0xe4,0x64,0x9b,0x93,0x4c,0xa4,0x95,0x99,0x1b,
        0x78,0x52,0xb8,0x55 };
    sha256("", 0, out);
    check("SHA-256('')", out, empty, 32);

    /* SHA-256 dwoch blokow (448+ bitow) - test dopelnienia */
    static const uint8_t twoblk[] = {
        0x24,0x8d,0x6a,0x61,0xd2,0x06,0x38,0xb8,0xe5,0xc0,0x26,0x93,0x0c,0x3e,
        0x60,0x39,0xa3,0x3c,0xe4,0x59,0x64,0xff,0x21,0x67,0xf6,0xec,0xed,0xd4,
        0x19,0xdb,0x06,0xc1 };
    sha256("abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq", 56, out);
    check("SHA-256 (dwa bloki)", out, twoblk, 32);

    /* HMAC-SHA256, przypadek 1 z RFC 4231 */
    uint8_t key[20];
    for (int i = 0; i < 20; i++)
        key[i] = 0x0b;
    static const uint8_t hmac1[] = {
        0xb0,0x34,0x4c,0x61,0xd8,0xdb,0x38,0x53,0x5c,0xa8,0xaf,0xce,0xaf,0x0b,
        0xf1,0x2b,0x88,0x1d,0xc2,0x00,0xc9,0x83,0x3d,0xa7,0x26,0xe9,0x37,0x6c,
        0x2e,0x32,0xcf,0xf7 };
    hmac_sha256(key, 20, "Hi There", 8, out);
    check("HMAC-SHA256 (RFC 4231 #1)", out, hmac1, 32);

    /* HMAC z kluczem dluzszym niz blok - przypadek 6 z RFC 4231 */
    static uint8_t longkey[131];
    for (int i = 0; i < 131; i++)
        longkey[i] = 0xaa;
    static const uint8_t hmac6[] = {
        0x60,0xe4,0x31,0x59,0x1e,0xe0,0xb6,0x7f,0x0d,0x8a,0x26,0xaa,0xcb,0xf5,
        0xb7,0x7f,0x8e,0x0b,0xc6,0x21,0x37,0x28,0xc5,0x14,0x05,0x46,0x04,0x0f,
        0x0e,0xe3,0x7f,0x54 };
    hmac_sha256(longkey, 131,
                "Test Using Larger Than Block-Size Key - Hash Key First", 54,
                out);
    check("HMAC-SHA256 (RFC 4231 #6)", out, hmac6, 32);

    /* HKDF-SHA256, przypadek 1 z RFC 5869 */
    uint8_t ikm[22], salt[13], info[10], prk[32];
    for (int i = 0; i < 22; i++)
        ikm[i] = 0x0b;
    for (int i = 0; i < 13; i++)
        salt[i] = (uint8_t)i;
    for (int i = 0; i < 10; i++)
        info[i] = (uint8_t)(0xf0 + i);

    static const uint8_t want_prk[] = {
        0x07,0x77,0x09,0x36,0x2c,0x2e,0x32,0xdf,0x0d,0xdc,0x3f,0x0d,0xc4,0x7b,
        0xba,0x63,0x90,0xb6,0xc7,0x3b,0xb5,0x0f,0x9c,0x31,0x22,0xec,0x84,0x4a,
        0xd7,0xc2,0xb3,0xe5 };
    hkdf_extract(salt, 13, ikm, 22, prk);
    check("HKDF-Extract (RFC 5869 #1)", prk, want_prk, 32);

    static const uint8_t want_okm[] = {
        0x3c,0xb2,0x5f,0x25,0xfa,0xac,0xd5,0x7a,0x90,0x43,0x4f,0x64,0xd0,0x36,
        0x2f,0x2a,0x2d,0x2d,0x0a,0x90,0xcf,0x1a,0x5a,0x4c,0x5d,0xb0,0x2d,0x56,
        0xec,0xc4,0xc5,0xbf,0x34,0x00,0x72,0x08,0xd5,0xb8,0x87,0x18,0x58,0x65 };
    hkdf_expand(prk, info, 10, out, 42);
    check("HKDF-Expand (RFC 5869 #1)", out, want_okm, 42);

    if (failures) {
        print("[crypto] BLEDOW: ");
        print_dec((uint32_t)failures);
        print("\n");
        sys_exit(1);
    }
    print("[crypto] wszystkie wektory zgadzaja sie\n");
    sys_exit(0);
}
